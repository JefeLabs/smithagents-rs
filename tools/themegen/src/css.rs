//! Tailwind v4 CSS generation from the design tokens.

use std::fmt::Write;

use smithagents_theme::color::fmt_num;
use smithagents_theme::tokens::{Appearance, ThemeSet, COLOR_TOKENS};

/// Renders the full generated stylesheet. Output is deterministic.
pub fn render_css(set: &ThemeSet) -> String {
    let base = &set.base;
    let mut out = String::new();
    out.push_str("/* GENERATED by themegen from design/tokens. Do not edit. */\n\n");

    out.push_str("@theme inline {\n");
    for token in COLOR_TOKENS {
        let _ = writeln!(out, "  --color-{token}: var(--{token});");
    }
    out.push_str("  --color-agent: oklch(var(--agent-l) var(--agent-c) var(--agent-h, 250));\n");
    out.push_str("  --radius-sm: calc(var(--radius) - 4px);\n");
    out.push_str("  --radius-md: calc(var(--radius) - 2px);\n");
    out.push_str("  --radius-lg: var(--radius);\n");
    out.push_str("  --radius-xl: calc(var(--radius) + 4px);\n");
    let _ = writeln!(out, "  --spacing: {}rem;", fmt_num(base.spacing_rem));
    for (name, rem) in &base.text_sizes_rem {
        let _ = writeln!(out, "  --text-{name}: {}rem;", fmt_num(*rem));
    }
    out.push_str("  --font-sans: var(--smith-font-sans);\n");
    out.push_str("  --font-mono: var(--smith-font-mono);\n");
    out.push_str("}\n");

    for theme in &set.themes {
        let selector = if theme.id == base.system_pair.dark {
            format!(":where(:root), [data-theme=\"{}\"]", theme.id)
        } else {
            format!("[data-theme=\"{}\"]", theme.id)
        };
        let scheme = match theme.appearance {
            Appearance::Dark => "dark",
            Appearance::Light => "light",
        };
        let _ = write!(out, "\n{selector} {{\n  color-scheme: {scheme};\n");
        for token in COLOR_TOKENS {
            if let Some(color) = theme.colors.get(*token) {
                let _ = writeln!(out, "  --{token}: {};", color.css());
            }
        }
        let _ = writeln!(out, "  --agent-l: {};", fmt_num(theme.agent.l));
        let _ = writeln!(out, "  --agent-c: {};", fmt_num(theme.agent.c));
        let _ = writeln!(out, "  --radius: {}px;", fmt_num(base.radius_px));
        out.push_str("}\n");
    }

    for (i, font) in base.fonts.iter().enumerate() {
        // The first font doubles as a zero-specificity fallback for pages
        // without a `data-font` attribute.
        let selector = if i == 0 {
            format!(":where(:root), [data-font=\"{}\"]", font.id)
        } else {
            format!("[data-font=\"{}\"]", font.id)
        };
        let _ = write!(
            out,
            "\n{selector} {{\n  --smith-font-sans: {};\n  --smith-font-mono: {};\n}}\n",
            font.sans, font.mono
        );
    }

    out.push_str("\nhtml { font-size: calc(16px * var(--text-scale, 1)); }\n");
    out
}
