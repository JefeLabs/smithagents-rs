use smithagents_theme::tokens::{ThemeSet, COLOR_TOKENS};
use themegen::css::render_css;

/// Returns the body of the block whose selector line contains `selector`.
fn block<'a>(css: &'a str, selector: &str) -> &'a str {
    let start = css
        .lines()
        .position(|l| l.contains(selector) && l.ends_with('{'))
        .unwrap_or_else(|| panic!("no block for {selector}"));
    let rest: Vec<&str> = css.lines().skip(start + 1).collect();
    let end = rest.iter().position(|l| *l == "}").unwrap();
    let offset: usize = css.lines().take(start + 1).map(|l| l.len() + 1).sum();
    let len: usize = rest[..end].iter().map(|l| l.len() + 1).sum();
    &css[offset..offset + len]
}

#[test]
fn renders_embedded_themes() {
    let css = render_css(ThemeSet::embedded());
    assert!(css.starts_with("/* GENERATED by themegen from design/tokens. Do not edit. */\n"));
    assert!(css.ends_with("}\n"));
    assert!(!css.contains('\r'));
    assert_eq!(css.matches("[data-theme=\"smith-dark\"]").count(), 1);
    assert_eq!(css.matches("[data-theme=\"smith-light\"] {").count(), 1);
    assert!(css.contains("--background: oklch(0.18 0.01 260);"));
    assert!(css.contains("--color-background: var(--background);"));
    assert!(css.contains("color-scheme: light;"));
    assert!(
        css.contains("--color-agent: oklch(var(--agent-l) var(--agent-c) var(--agent-h, 250));")
    );
    assert!(css.contains("--radius-md: calc(var(--radius) - 2px);"));
    assert!(css.contains("--spacing: 0.25rem;"));
    assert!(css.contains("--text-xs: 0.75rem;"));
    assert!(css.contains("--font-sans: var(--smith-font-sans);"));
    assert!(css.contains("--font-mono: var(--smith-font-mono);"));
    assert!(!css.contains("--font-sans: var(--font-sans);"));
    assert!(css.contains("[data-font=\"mono\"] {"));
    let first = &ThemeSet::embedded().base.fonts[0].id;
    assert!(css.contains(&format!(
        ":where(:root), [data-font=\"{first}\"] {{\n  --smith-font-sans:"
    )));
    assert!(css.contains("  --smith-font-mono:"));
    assert!(css.contains("html { font-size: calc(16px * var(--text-scale, 1)); }"));
    assert!(css.contains(":where(:root), [data-theme=\"smith-dark\"] {"));
    assert!(!css.contains(":root, [data-theme"));
}

#[test]
fn every_token_in_every_theme_block() {
    let css = render_css(ThemeSet::embedded());
    for sel in [
        "[data-theme=\"smith-dark\"]",
        "[data-theme=\"smith-light\"]",
    ] {
        let b = block(&css, sel);
        for t in COLOR_TOKENS {
            assert!(b.contains(&format!("--{t}: oklch(")), "{sel} lacks {t}");
        }
        assert!(
            b.contains("--agent-l:") && b.contains("--agent-c:") && b.contains("--radius: 8px;")
        );
    }
}

#[test]
fn deterministic() {
    let set = ThemeSet::embedded();
    assert_eq!(render_css(set), render_css(set));
}

#[test]
fn third_theme_needs_no_code_change() {
    let dir = tempfile::tempdir().unwrap();
    let src = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../design/tokens");
    std::fs::create_dir(dir.path().join("themes")).unwrap();
    for f in ["base.json", "agent-palette.json"] {
        std::fs::copy(src.join(f), dir.path().join(f)).unwrap();
    }
    for f in ["smith-dark.json", "smith-light.json"] {
        std::fs::copy(
            src.join("themes").join(f),
            dir.path().join("themes").join(f),
        )
        .unwrap();
    }
    let light = std::fs::read_to_string(src.join("themes/smith-light.json")).unwrap();
    let third = light
        .replace("\"smith-light\"", "\"smith-third\"")
        .replace("Smith Light", "Smith Third");
    std::fs::write(dir.path().join("themes/smith-third.json"), third).unwrap();
    let set = ThemeSet::load_dir(dir.path()).unwrap();
    let css = render_css(&set);
    assert_eq!(css.matches("[data-theme=").count(), 3);
    assert!(css.contains("[data-theme=\"smith-third\"] {"));
}

#[test]
fn dark_fallback_cannot_outrank_earlier_sorting_theme() {
    let dir = tempfile::tempdir().unwrap();
    let src = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../design/tokens");
    std::fs::create_dir(dir.path().join("themes")).unwrap();
    for f in ["base.json", "agent-palette.json"] {
        std::fs::copy(src.join(f), dir.path().join(f)).unwrap();
    }
    for f in ["smith-dark.json", "smith-light.json"] {
        std::fs::copy(
            src.join("themes").join(f),
            dir.path().join("themes").join(f),
        )
        .unwrap();
    }
    let light = std::fs::read_to_string(src.join("themes/smith-light.json")).unwrap();
    let third = light
        .replace("\"smith-light\"", "\"aurora\"")
        .replace("Smith Light", "Aurora");
    std::fs::write(dir.path().join("themes/aurora.json"), third).unwrap();
    let css = render_css(&ThemeSet::load_dir(dir.path()).unwrap());
    let aurora = css.find("[data-theme=\"aurora\"] {").unwrap();
    let dark = css.find("[data-theme=\"smith-dark\"] {").unwrap();
    assert!(aurora < dark, "aurora block must come first");
    // The :root fallback has zero specificity, so [data-theme] always wins.
    assert!(css.contains(":where(:root), [data-theme=\"smith-dark\"] {"));
    assert!(!css.contains(":root, [data-theme"));
}
